#!/usr/bin/env node
// Mirrors the user docs (docs/) into a checkout of the GitHub Wiki (forge-engineering → user-docs §1).
// The repo is the source; the wiki is a generated copy. No dependencies.
// Usage: node scripts/docs-to-wiki.mjs <docsDir> <wikiDir> [--repo owner/name]
//   docs/index.md → Home.md · how-to/, reference/, about/, getting-started.md → <H1-as-wiki-name>.md
//   docs/API.md (if present) → For-developers.md · docs/images/** → images/** · _Sidebar.md, _Footer.md
// Developer docs (SPEC, PLAN, DECISIONS, ARCHITECTURE, ASSETS, LISTINGS, …) are not mirrored.
// Only files this script wrote are ever updated or deleted: pages carry MARKER, images are listed
// in MANIFEST.
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, posix, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

export const MARKER = "<!-- generated by scripts/docs-to-wiki.mjs from docs/ — do not edit in the wiki -->";
export const MANIFEST = ".docs-to-wiki.json";
const USER_DIRS = ["how-to", "reference", "about"];
const GROUPS = { "how-to": "How-to guides", reference: "Reference", about: "About" };

/** Lists files under `dir` (recursive) as POSIX paths relative to `dir`. */
function walk(dir, base = dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full, base) : [relative(base, full).split(sep).join("/")];
  });
}

/** Returns a wiki page name from a title: "Create teams" → "Create-teams". */
export function wikiName(title) {
  return title.trim().replace(/[\\/:*?"<>|#%[\]`]+/g, "").replace(/\s+/g, "-").replace(/-+/g, "-").replace(/^-|-$/g, "") || "Page";
}

/** Returns the H1 text of a Markdown page, if any. */
function h1(md) {
  return /^# (.+)$/m.exec(md)?.[1]?.trim();
}

/** Returns the source pages to mirror: { src (relative to docs), name (wiki page) }. */
export function plan(docsDir) {
  const pages = [];
  if (existsSync(join(docsDir, "index.md"))) pages.push({ src: "index.md", name: "Home" });
  const user = [
    ...(existsSync(join(docsDir, "getting-started.md")) ? ["getting-started.md"] : []),
    ...USER_DIRS.flatMap((d) => walk(join(docsDir, d)).filter((f) => f.endsWith(".md")).sort().map((f) => `${d}/${f}`)),
  ];
  for (const src of user) pages.push({ src, name: wikiName(h1(readFileSync(join(docsDir, src), "utf8")) ?? posix.basename(src, ".md")) });
  if (existsSync(join(docsDir, "API.md"))) pages.push({ src: "API.md", name: "For-developers" });
  const seen = new Set();
  for (const p of pages) {
    if (seen.has(p.name)) throw new Error(`docs-to-wiki: two pages map to the wiki name "${p.name}" (${p.src}) — give them different H1s.`);
    seen.add(p.name);
  }
  return pages;
}

/**
 * Rewrites one page for the wiki: links to mirrored pages → wiki names, images → images/…,
 * links to other repo files → the file on GitHub (when `repo` is known). <picture> is kept.
 */
export function convert(md, src, pages, repo) {
  const bySrc = new Map(pages.map((p) => [p.src, p.name]));
  const resolve = (target) => posix.normalize(posix.join(posix.dirname(src), target));
  const rewrite = (target) => {
    if (/^([a-z][a-z0-9+.-]*:|#|\/)/i.test(target)) return target; // absolute URL, anchor or root path
    const [path = "", hash = ""] = target.split(/(?=#)/);
    const abs = resolve(path);
    if (abs.startsWith("images/")) return abs + hash;
    const page = bySrc.get(abs);
    if (page) return page + hash;
    if (!repo) return target;
    return `https://github.com/${repo}/blob/HEAD/${posix.normalize(posix.join("docs", abs))}${hash}`;
  };
  const body = md
    .replace(/(!?\[[^\]]*\]\()([^)\s]+)((?:\s+"[^"]*")?\))/g, (_, a, t, b) => `${a}${rewrite(t)}${b}`)
    .replace(/\b(src|srcset)="([^"]+)"/g, (_, attr, t) => `${attr}="${rewrite(t)}"`);
  return `${MARKER}\n\n${body.trimEnd()}\n`;
}

/** Builds _Sidebar.md: Home, then the index's groups; pages the index doesn't list join their folder's group. */
export function sidebar(docsDir, pages) {
  const byName = new Map(pages.map((p) => [p.src, p.name]));
  const titleOf = (p) => (p.src === "API.md" ? "For developers" : h1(readFileSync(join(docsDir, p.src), "utf8")) ?? p.name.replaceAll("-", " "));
  const groups = new Map(); // heading → link lines, in order
  const add = (group, line) => groups.set(group, [...(groups.get(group) ?? []), line]);
  const listed = new Set(["index.md"]);
  const index = existsSync(join(docsDir, "index.md")) ? readFileSync(join(docsDir, "index.md"), "utf8") : "";
  for (const section of index.split(/^## /m).slice(1)) {
    const [heading = "", ...rest] = section.split("\n");
    for (const [, text, target] of rest.join("\n").matchAll(/\[([^\]]+)\]\(([^)#\s]+)[^)]*\)/g)) {
      const src = posix.normalize(target ?? "");
      if (!byName.has(src) || listed.has(src)) continue;
      listed.add(src);
      add(heading.trim(), `- [${text}](${byName.get(src)})`);
    }
  }
  const SPECIAL = { "API.md": "For developers", "getting-started.md": "Getting started" };
  const folderGroup = (src) => SPECIAL[src] ?? GROUPS[src.split("/")[0]] ?? "More";
  for (const p of pages.filter((q) => !listed.has(q.src))) add(folderGroup(p.src), `- [${titleOf(p)}](${p.name})`);
  const lines = [MARKER, "", "**[Home](Home)**", ""];
  for (const [heading, links] of groups) lines.push(`**${heading}**`, ...links, "");
  return `${lines.join("\n").trimEnd()}\n`;
}

export const FOOTER = `${MARKER}\n\nGenerated from docs/ in the repository — edit there, not here.\n`;

/** Mirrors docsDir into wikiDir; returns { written, removed } (wiki-relative paths). */
export function mirror(docsDir, wikiDir, repo) {
  const pages = plan(docsDir);
  const out = new Map(pages.map((p) => [`${p.name}.md`, convert(readFileSync(join(docsDir, p.src), "utf8"), p.src, pages, repo)]));
  out.set("_Sidebar.md", sidebar(docsDir, pages));
  out.set("_Footer.md", FOOTER);
  const images = walk(join(docsDir, "images")).map((f) => `images/${f}`);
  mkdirSync(wikiDir, { recursive: true });
  const written = [];
  for (const [file, text] of out) {
    const target = join(wikiDir, file);
    if (existsSync(target)) {
      const current = readFileSync(target, "utf8");
      // Home.md is the "first page" GitHub needs before the wiki repo exists: always ours to replace.
      if (!current.startsWith(MARKER) && file !== "Home.md") throw new Error(`docs-to-wiki: ${file} exists in the wiki but was not generated — rename the docs page or move the wiki page.`);
      if (current === text) continue;
    }
    writeFileSync(target, text);
    written.push(file);
  }
  for (const img of images) {
    const target = join(wikiDir, img);
    const data = readFileSync(join(docsDir, img));
    if (existsSync(target) && readFileSync(target).equals(data)) continue;
    mkdirSync(dirname(target), { recursive: true });
    copyFileSync(join(docsDir, img), target);
    written.push(img);
  }
  // Remove what this script made before and no longer has a source.
  const removed = [];
  for (const file of readdirSync(wikiDir).filter((f) => f.endsWith(".md") && !out.has(f))) {
    if (readFileSync(join(wikiDir, file), "utf8").startsWith(MARKER)) { rmSync(join(wikiDir, file)); removed.push(file); }
  }
  const manifestPath = join(wikiDir, MANIFEST);
  const before = existsSync(manifestPath) ? JSON.parse(readFileSync(manifestPath, "utf8")).images ?? [] : [];
  for (const img of before.filter((f) => !images.includes(f) && existsSync(join(wikiDir, f)))) { rmSync(join(wikiDir, img)); removed.push(img); }
  const manifest = `${JSON.stringify({ note: "Files written by scripts/docs-to-wiki.mjs", images }, null, 2)}\n`;
  if (!existsSync(manifestPath) || readFileSync(manifestPath, "utf8") !== manifest) writeFileSync(manifestPath, manifest);
  return { written, removed };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const [docsDir, wikiDir] = process.argv.slice(2).filter((a, i, all) => !a.startsWith("--") && all[i - 1] !== "--repo");
  const repoArg = process.argv.indexOf("--repo");
  const repo = repoArg > 0 ? process.argv[repoArg + 1] : process.env.GITHUB_REPOSITORY;
  if (!docsDir || !wikiDir) { console.error("Usage: node scripts/docs-to-wiki.mjs <docsDir> <wikiDir> [--repo owner/name]"); process.exit(2); }
  const { written, removed } = mirror(docsDir, wikiDir, repo);
  console.log(`docs-to-wiki: ${String(written.length)} written, ${String(removed.length)} removed${written.length + removed.length ? `\n  ${[...written, ...removed.map((f) => `- ${f}`)].join("\n  ")}` : ""}`);
}
